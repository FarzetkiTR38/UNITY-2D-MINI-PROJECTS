        private static Sprite GetOrCreate(string name, int atlas, Rect sourceRect, Vector2[] sourceVertices, ushort[] triangles)
        {
            if (Application.isPlaying) throw new InvalidOperationException("Author rich theme sprites in Edit Mode only.");
            string path = Folder + "Settings" + name + ".asset";
            var existing = AssetDatabase.LoadAssetAtPath<Sprite>(path);
            var texture = AssetDatabase.LoadAssetAtPath<Texture2D>(Source + "ChatGPT Image 26 Ağu 2026 01_03_39 (" + atlas + ").png");
            if (texture == null) throw new InvalidOperationException("Original Settings theme atlas missing.");
            var scale = new Vector2(texture.width / 2172f, texture.height / 724f);
            var rect = new Rect(sourceRect.x * scale.x, sourceRect.y * scale.y, sourceRect.width * scale.x, sourceRect.height * scale.y);
            var vertices = new Vector2[sourceVertices.Length];
            for (int i = 0; i < vertices.Length; i++)
            {
                var v = Vector2.Scale(sourceVertices[i], scale);
                vertices[i] = new Vector2(Mathf.Clamp(v.x, 0, rect.width), Mathf.Clamp(v.y, 0, rect.height));
            }
            var sprite = existing;
            if (sprite == null)
            {
                sprite = Sprite.Create(texture, rect, new Vector2(.5f, .5f), 100, 0, SpriteMeshType.FullRect);
                sprite.name = "Settings" + name;
                AssetDatabase.CreateAsset(sprite, path);
            }
            var positions = new NativeArray<Vector3>(vertices.Length, Allocator.Temp);
            var uvs = new NativeArray<Vector2>(vertices.Length, Allocator.Temp);
            var indices = new NativeArray<ushort>(triangles, Allocator.Temp);
            try
            {
                for (int i = 0; i < vertices.Length; i++)
                {
                    positions[i] = (Vector3)((vertices[i] - rect.size * .5f) / sprite.pixelsPerUnit);
                    uvs[i] = new Vector2((rect.x + vertices[i].x) / texture.width, (rect.y + vertices[i].y) / texture.height);
                }
                sprite.SetVertexCount(vertices.Length);
                sprite.SetVertexAttribute(VertexAttribute.Position, positions);
                sprite.SetVertexAttribute(VertexAttribute.TexCoord0, uvs);
                sprite.SetIndices(indices);
            }
            finally
            {
                positions.Dispose(); uvs.Dispose(); indices.Dispose();
            }
            EditorUtility.SetDirty(sprite); AssetDatabase.SaveAssetIfDirty(sprite);
            return sprite;
        }
